"""Audio assembly: narration + SFX + music (ducked under the voice), then
voice polish and two-pass loudness normalisation to -14 LUFS with FFmpeg."""
from __future__ import annotations

import json
import re
import subprocess
import wave
from math import gcd
from pathlib import Path

import numpy as np
from scipy.signal import resample_poly

from . import sfx
from .music import SR, licensed_tracks, procedural_track


def resample(x: np.ndarray, sr_in: int, sr_out: int = SR) -> np.ndarray:
    if sr_in == sr_out:
        return x.astype(np.float32)
    g = gcd(sr_in, sr_out)
    return resample_poly(x, sr_out // g, sr_in // g).astype(np.float32)


def write_wav(path: str | Path, data: np.ndarray, sr: int = SR) -> None:
    data = np.clip(data, -1, 1)
    if data.ndim == 1:
        data = data[:, None]
    pcm = (data * 32767).astype(np.int16)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(pcm.shape[1])
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(pcm.tobytes())


def place(track: np.ndarray, clip: np.ndarray, at_seconds: float, gain: float = 1.0) -> None:
    start = int(round(at_seconds * SR))
    if start >= track.size:
        return
    if start < 0:
        clip, start = clip[-start:], 0
    end = min(start + clip.size, track.size)
    track[start:end] += clip[: end - start] * gain


def envelope(x: np.ndarray, attack: float = 0.02, release: float = 0.35) -> np.ndarray:
    """Smoothed amplitude follower (for ducking music under the voice)."""
    hop = 480
    n = int(np.ceil(x.size / hop))
    padded = np.zeros(n * hop, np.float32)
    padded[: x.size] = np.abs(x)
    rms = padded.reshape(n, hop).max(axis=1)
    a_up = np.exp(-hop / (attack * SR))
    a_dn = np.exp(-hop / (release * SR))
    out = np.zeros(n, np.float32)
    level = 0.0
    for i, v in enumerate(rms):
        coef = a_up if v > level else a_dn
        level = coef * level + (1 - coef) * v
        out[i] = level
    out /= out.max() + 1e-9
    return np.repeat(out, hop)[: x.size]


def build_stems(timeline, total_seconds: float, settings: dict, seed: int, workdir: Path) -> dict:
    """timeline: list of TimedScene with .audio list of (offset_seconds, samples, sr)."""
    n = int(round(total_seconds * SR))
    voice = np.zeros(n, np.float32)
    for ts in timeline:
        for offset, samples, sr in ts.audio:
            place(voice, resample(samples, sr), offset)
    fx = np.zeros(n, np.float32)
    for ts in timeline[1:]:
        place(fx, sfx.whoosh(0.36, seed + ts.index), ts.start - 0.30, 0.45)
    for ts in timeline:
        if ts.scene.badge in ("RUMOR", "MYTH"):
            place(fx, sfx.alert(), ts.start + 0.12, 0.35)
        elif ts.scene.badge:
            place(fx, sfx.pop(1180), ts.start + 0.12, 0.25)
        if ts.scene.big:
            place(fx, sfx.pop(520, 0.18), ts.start + 0.05, 0.4)
    if len(timeline) > 1:
        place(fx, sfx.riser(0.8, seed), timeline[-1].start - 0.8, 0.5)

    music_info: dict = {"mode": "off"}
    music = np.zeros(n, np.float32)
    mode = settings["music"].get("mode", "off")
    if mode == "procedural":
        music = procedural_track(total_seconds, seed)
        music_info = {"mode": "procedural", "seed": seed, "license": "original, generated by this project"}
    elif mode == "licensed":
        tracks = licensed_tracks(settings.get("_music_dir", "assets/music"))
        if tracks:
            pick = tracks[seed % len(tracks)]
            music = load_audio(pick["path"], n)
            music_info = {"mode": "licensed", **{k: pick[k] for k in pick if k != "path"}}
    if music.any():
        env = envelope(voice)
        active = voice[env > 0.15]
        voice_rms = float(np.sqrt(np.mean(active ** 2))) if active.size else 0.1
        music_rms = float(np.sqrt(np.mean(music ** 2))) + 1e-9
        level = 10 ** (float(settings["music"].get("volume_db", -15)) / 20)   # relative to the voice
        music = music * (voice_rms * level / music_rms) * (1.0 - 0.45 * env)
    paths = {"voice": workdir / "voice.wav", "bed": workdir / "bed.wav"}
    write_wav(paths["voice"], voice)
    write_wav(paths["bed"], np.clip(fx + music, -1, 1))
    return {"paths": paths, "music": music_info}


def load_audio(path: str, n: int) -> np.ndarray:
    raw = subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", path, "-ac", "1", "-ar", str(SR),
                          "-f", "f32le", "-"], capture_output=True, check=True).stdout
    x = np.frombuffer(raw, np.float32)
    if x.size < n:
        x = np.tile(x, int(np.ceil(n / max(x.size, 1))))
    return x[:n].copy()


VOICE_CHAIN = ("highpass=f=75,acompressor=threshold=0.12:ratio=3:attack=4:release=90:makeup=1.6,"
               "equalizer=f=3200:t=q:w=1.1:g=2.5,equalizer=f=220:t=q:w=1.0:g=-1.5")


def _loudnorm_measure(cmd_inputs: list[str], graph: str) -> dict:
    proc = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", *cmd_inputs, "-filter_complex",
                           graph + ",loudnorm=I=-14:TP=-1.5:LRA=11:print_format=json[out]", "-map", "[out]",
                           "-f", "null", "-"], capture_output=True, text=True, check=True)
    m = re.search(r"\{[^{}]*\"input_i\"[^{}]*\}", proc.stderr, re.S)
    if not m:
        raise RuntimeError("loudnorm measurement failed")
    return json.loads(m.group(0))


def master(stems: dict, out_path: Path, target_lufs: float = -14.0, total_seconds: float | None = None) -> dict:
    """Voice chain + mix + 2-pass loudnorm -> AAC 48 kHz stereo."""
    voice, bed = str(stems["paths"]["voice"]), str(stems["paths"]["bed"])
    inputs = ["-i", voice, "-i", bed]
    graph = f"[0:a]{VOICE_CHAIN}[v];[v][1:a]amix=inputs=2:normalize=0:duration=longest"
    m = _loudnorm_measure(inputs, graph)
    ln = (f"loudnorm=I={target_lufs}:TP=-1.5:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:"
          f"measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}:"
          f"linear=true")
    trim = f",atrim=0:{total_seconds:.3f}" if total_seconds else ""
    tmp = out_path.with_name(out_path.stem + ".tmp.m4a")
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *inputs, "-filter_complex",
                    f"{graph},{ln},aresample=48000,aformat=channel_layouts=stereo{trim}[out]", "-map", "[out]",
                    "-c:a", "aac", "-b:a", "192k", str(tmp)], check=True)
    tmp.replace(out_path)
    return {"measured_input_lufs": float(m["input_i"])}
